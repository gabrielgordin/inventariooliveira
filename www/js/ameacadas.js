/* Busca pelo nome científico. Devolve:
   {especie, cat, catNome}  quando a espécie está na lista;
   {genero: true}           quando só o gênero foi identificado (sp./spp.) e o gênero tem espécies ameaçadas;
   null                     nos demais casos. */
window.AMEACADAS.buscar = function (cientifico) {
  const A = window.AMEACADAS;
  if (!A._idx) { A._idx = {}; Object.keys(A.especies).forEach(k => { A._idx[k.toLowerCase()] = k; }); A._gen = new Set(A.generos.map(g => g.toLowerCase())); }
  let c = String(cientifico || '').replace(/\(.*?\)/g, '').replace(/\s+/g, ' ').trim().toLowerCase();
  if (!c) return null;
  const k = A._idx[c];
  if (k) return { especie: k, cat: A.especies[k], catNome: A.categorias[A.especies[k]] };
  const p = c.split(' ');
  if (A._gen.has(p[0]) && (p.length === 1 || /^spp?\.?$/.test(p[1]))) return { genero: true, nome: p[0][0].toUpperCase() + p[0].slice(1) };
  return null;
};
